// Generates supabase/seed.sql from src/data.js so the database starts with the prototype's content.
// Run: npm run gen:seed   (tests/db/seed.test.js fails if the committed file is stale)
import fs from 'node:fs'
import crypto from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { initialQuestions, initialTests, CHOICES } from '../src/data.js'

const NS = Buffer.from('6ba7b8109dad11d180b400c04fd430c8', 'hex')
export const uuid5 = (name) => {
  const h = crypto.createHash('sha1').update(NS).update(name).digest()
  h[6] = (h[6] & 0x0f) | 0x50
  h[8] = (h[8] & 0x3f) | 0x80
  const x = h.subarray(0, 16).toString('hex')
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`
}
const qid = (id) => uuid5('bioprep:question:' + id)
const tid = (id) => uuid5('bioprep:test:' + id)
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`
const arr = (a) => `array[${a.map(lit).join(', ')}]::text[]`

export function buildSeed() {
  const out = ['-- GENERATED by scripts/gen-seed.mjs from src/data.js. Do not edit by hand.', '']
  for (const q of initialQuestions) {
    out.push(
      `insert into public.questions (id, subject, chapter, difficulty, text, options, status) values (${lit(qid(q.id))}, ${lit(q.subject)}, ${lit(q.chapter)}, ${lit(q.difficulty)}, ${lit(q.text)}, ${json(q.options)}, ${lit(q.status)}) on conflict (id) do nothing;`,
      `insert into public.question_secrets (question_id, correct, explanation, why_wrong, recap, ncert, caption) values (${lit(qid(q.id))}, ${q.correct}, ${lit(q.explanation)}, ${json(q.whyWrong)}, ${json(q.recap)}, ${lit(q.ncert)}, ${lit(q.caption)}) on conflict (question_id) do nothing;`,
    )
    q.socratic.forEach((s, i) => {
      // CHOICES lists the correct tap option first; the API shuffles before sending.
      out.push(
        `insert into public.socratic_steps (question_id, position, ask, keys, hint, good, sample, choices) values (${lit(qid(q.id))}, ${i + 1}, ${lit(s.ask)}, ${arr(s.keys)}, ${lit(s.hint)}, ${lit(s.good)}, ${lit(s.sample)}, ${arr(CHOICES[`${q.id}:${i}`] || [])}) on conflict (question_id, position) do nothing;`,
      )
    })
  }
  for (const t of initialTests) {
    out.push(
      `insert into public.tests (id, title, kind, duration_minutes, price_inr, published) values (${lit(tid(t.id))}, ${lit(t.title)}, ${lit(t.kind)}, ${t.duration}, ${t.price}, ${t.published}) on conflict (id) do nothing;`,
    )
    t.qids.forEach((id, i) => {
      out.push(`insert into public.test_questions (test_id, question_id, position) values (${lit(tid(t.id))}, ${lit(qid(id))}, ${i + 1}) on conflict (test_id, question_id) do nothing;`)
    })
  }
  return out.join('\n') + '\n'
}

const here = path.dirname(fileURLToPath(import.meta.url))
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(here, '../supabase/seed.sql'), buildSeed())
  console.log('wrote supabase/seed.sql')
}
