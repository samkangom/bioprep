test('Hindi can be selected and persists; Meiteilon is not offered until translated', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('option', { name: /Meiteilon/ })).toBeDisabled()
  await page.getByLabel('Language').selectOption('hi')
  await expect(page.getByRole('heading', { name: /में आपका स्वागत है/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'कोड भेजें' })).toBeVisible()
  await page.getByLabel('भाषा').selectOption('en')
})

test('download my data, then delete my account and data', async ({ page }) => {
  const phone = newPhone()
  await signIn(page, { phone, name: 'Gone' })
  await page.getByRole('button', { name: 'Gone' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download my data' }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('my-bioprep-data.json')
  await page.getByRole('button', { name: 'Delete my account and data' }).click()
  const confirm = page.getByRole('button', { name: 'Delete everything' })
  await expect(confirm).toBeDisabled()
  await page.getByLabel('Type DELETE to confirm').fill('DELETE')
  await confirm.click()
  await expect(page.getByRole('heading', { name: /Welcome to BioPrep/ })).toBeVisible()
  // signing in again with the same number starts from scratch (a new account, asked to introduce yourself)
  await page.getByLabel('Mobile number').fill(phone)
  await page.getByRole('button', { name: 'Send code' }).click()
  await page.getByLabel('6-digit code').fill('123456')
  await page.getByRole('button', { name: 'Verify and continue' }).click()
  await expect(page.getByRole('heading', { name: 'About you' })).toBeVisible()
})
