import { test, expect } from '@playwright/test'
import { signIn, newPhone } from './helpers.js'

test('under-18 sign-up needs a parent or guardian, then works', async ({ page }) => {
  const year = new Date().getFullYear() - 16
  await page.goto('/')
  await page.getByLabel('Mobile number').fill(newPhone())
  await page.getByRole('button', { name: 'Send code' }).click()
  await page.getByLabel('6-digit code').fill('123456')
  await page.getByRole('button', { name: 'Verify and continue' }).click()
  await page.getByLabel('Your name').fill('Teen')
  await page.getByLabel('Date of birth').fill(`${year}-03-10`)
  await expect(page.getByText('Parent or guardian consent (you are under 18)')).toBeVisible()
  await page.getByLabel(/I have read the/).check()
  await page.getByRole('button', { name: 'Start preparing' }).click()
  await expect(page.getByRole('alert')).toContainText('Enter your parent or guardian')
  await page.getByLabel('Their full name').fill('Sita Devi')
  await page.getByLabel('Their mobile number').fill('9822222222')
  await page.getByRole('button', { name: 'Start preparing' }).click()
  await expect(page.getByRole('alert')).toContainText('must agree')
  await page.getByLabel(/I am this student's parent/).check()
  await page.getByRole('button', { name: 'Start preparing' }).click()
  await expect(page.getByRole('heading', { name: /Hello, Teen/ })).toBeVisible()
})

test('under the minimum age is turned away; adults see no guardian fields', async ({ page }) => {
  const y = new Date().getFullYear()
  await page.goto('/')
  await page.getByLabel('Mobile number').fill(newPhone())
  await page.getByRole('button', { name: 'Send code' }).click()
  await page.getByLabel('6-digit code').fill('123456')
  await page.getByRole('button', { name: 'Verify and continue' }).click()
  await page.getByLabel('Your name').fill('Kid')
  await page.getByLabel('Date of birth').fill(`${y - 10}-01-01`)
  await page.getByLabel(/I have read the/).check()
  await page.getByRole('button', { name: 'Start preparing' }).click()
  await expect(page.getByRole('alert')).toContainText('aged 13 and above')
  await page.getByLabel('Date of birth').fill(`${y - 25}-01-01`)
  await expect(page.getByText('Parent or guardian consent')).toHaveCount(0)
})

